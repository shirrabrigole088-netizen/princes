    private void setDefaults() {
        this.jTFSectionName.setText("");
        this.selectedId = -1;
        this.jBtnAdd.setEnabled(true);
        this.jBtnUpdate.setEnabled(false);
        this.jBtnDelete.setEnabled(false);
    }

    private void setupListTable() {
        jTableSections.setModel(tableModel);
        // sorter => click a column header to sort (ID sorts numerically)
        jTableSections.setRowSorter(new TableRowSorter<>(tableModel));
        jTableSections.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        jTableSections.getTableHeader().setReorderingAllowed(false);
        jTableSections.createDefaultColumnsFromModel();
        jTableSections.getColumnModel().getColumn(0).setPreferredWidth(50);
        jTableSections.getColumnModel().getColumn(0).setMaxWidth(60);
        jTableSections.getColumnModel().getColumn(1).setPreferredWidth(200);
        jTableSections.setAutoResizeMode(javax.swing.JTable.AUTO_RESIZE_LAST_COLUMN);
    }

    private void setupRowsActionListener() {
        jTableSections.getSelectionModel().addListSelectionListener(e -> {
            if (e.getValueIsAdjusting()) {
                return; // FIX: the sample reset the form here
            }
            int selectedRow = jTableSections.getSelectedRow();
            if (selectedRow != -1) {
                int modelRow = jTableSections.convertRowIndexToModel(selectedRow);
                Section s = controller.getSectionDetails(tableModel.getSectionId(modelRow));
                if (s != null) {
                    displaySelectedSection(s);
                }
            }
        });
    }

    private void displaySelectedSection(Section s) {
        this.jTFSectionName.setText(s.getName());
        this.selectedId = s.getId();
        this.jBtnAdd.setEnabled(false);
        this.jBtnUpdate.setEnabled(true);
        this.jBtnDelete.setEnabled(true);
    }

    public void refreshSections() {
        List<Section> list = controller.getAllSections();
        tableModel.setSections(list);
    }

    private void save() {
        String err = (selectedId == -1)
                ? controller.handleAddSection(jTFSectionName.getText())
                : controller.handleUpdateSection(selectedId, jTFSectionName.getText());
        if (err != null) {
            JOptionPane.showMessageDialog(this, err, "Sections", JOptionPane.ERROR_MESSAGE);
            return;
        }
        jTableSections.clearSelection();
        setDefaults();
    }

    private void delete() {
        if (selectedId == -1) {
            return;
        }
        if (JOptionPane.showConfirmDialog(this, "Delete this section?", "Sections",
                JOptionPane.YES_NO_OPTION) != JOptionPane.YES_OPTION) {
            return;
        }
        String err = controller.handleDeleteSection(selectedId);
        if (err != null) {
            JOptionPane.showMessageDialog(this, err, "Sections", JOptionPane.ERROR_MESSAGE);
            return;
        }
        jTableSections.clearSelection();
        setDefaults();
    }

